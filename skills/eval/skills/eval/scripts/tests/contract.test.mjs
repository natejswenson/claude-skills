test('bookkeeping, thinking and injected reminders are dropped from a trace', () => {
  const jsonl = [
    JSON.stringify({ type: 'permission-mode', mode: 'default' }),
    JSON.stringify({ type: 'user', message: { role: 'user', content: 'do the thing <system-reminder>ignore me</system-reminder>' } }),
    JSON.stringify({
      type: 'assistant',
      message: { role: 'assistant', content: [{ type: 'thinking', thinking: 'private' }, { type: 'text', text: 'working' }] },
    }),
    JSON.stringify({
      type: 'assistant',
      message: { role: 'assistant', content: [{ type: 'tool_use', name: 'Bash', input: { command: 'ls' } }] },
    }),
  ].join('\n');

  const { events, dropped } = normalizeTranscript(jsonl);
  assert.equal(dropped.bookkeeping, 1);
  assert.equal(dropped.thinking, 1);
  assert.deepEqual(events.map((e) => e.kind), ['user', 'assistant', 'tool-use']);
  assert.equal(events[0].text, 'do the thing', 'an injected reminder was counted as something the user said');
  assert.equal(events[2].command, 'ls');
  assert.deepEqual(events.map((e) => e.id), ['e1', 'e2', 'e3']);
});

test('secrets never reach a fixture', () => {
  const masked = redact('token ghp_abcdefghijklmnopqrstuvwxyz012345 and sk-abcdefghijklmnopqrst');
  assert.doesNotMatch(masked, /ghp_abcdefghij/);
  assert.doesNotMatch(masked, /sk-abcdefghij/);
  assert.match(masked, /REDACTED/);
});

test('an unparseable line is counted, never silently skipped', () => {
  const { dropped } = normalizeTranscript('not json\n{"type":"system"}');
  assert.equal(dropped.unparsed, 1);
});

test('--grep matches literal substrings, never a compiled pattern', () => {
  // Regression: these lookups were built with `new RegExp(userInput)`, which
  // CodeQL correctly flagged as regex injection — a pathological pattern from a
  // script or a pasted command hangs the process. Metacharacters must now be
  // inert, and alternation is expressed with commas instead.
  const hit = literalMatcher('| tail, | awk');
  assert.ok(hit('npm test 2>&1 | tail -12'));
  assert.ok(hit("x | awk '{print}'"));
  assert.ok(!hit('npm test --silent'));

  const literal = literalMatcher('a|b');
  assert.ok(literal('contains a|b verbatim'), 'the pipe must be a character, not alternation');
  assert.ok(!literal('contains only a'), 'the pattern was compiled as a regex');

  assert.ok(literalMatcher('(a+)+$')('value (a+)+$ here'), 'a catastrophic-backtracking pattern must be inert text');
  assert.throws(() => literalMatcher('  ,  '), /at least one substring/);
});
