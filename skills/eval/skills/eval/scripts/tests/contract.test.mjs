import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { extractContract, clauseId } from '../lib/contract.mjs';
import { normalizeTranscript, redact, literalMatcher } from '../lib/trace.mjs';

/** A throwaway repo with one skill in it, shaped exactly like a real one. */
function fakeRepo(skillMd, invariants = null, claudeMd = null) {
  const root = mkdtempSync(join(tmpdir(), 'eval-contract-'));
  const dir = join(root, 'skills', 'widget', 'skills', 'widget');
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'SKILL.md'), skillMd);
  if (invariants) writeFileSync(join(dir, 'skill-invariants.json'), JSON.stringify(invariants, null, 2));
  if (claudeMd) writeFileSync(join(root, 'CLAUDE.md'), claudeMd);
  return root;
}

const textsOf = (c) => c.clauses.map((x) => x.text);

test('all three rule forms are extracted', () => {
  const repo = fakeRepo(`# widget

**Never hand-write a brand value.**

**Announce the skill once, at the start.**

**One script call, not a pipeline.**
`);
  const texts = textsOf(extractContract(repo, 'widget'));
  assert.ok(texts.includes('Never hand-write a brand value.'), 'prohibition form missed');
  assert.ok(texts.includes('Announce the skill once, at the start.'), 'positive imperative form missed');
  assert.ok(texts.includes('One script call, not a pipeline.'), 'contrastive form missed');
});

test('commentary is not a clause', () => {
  const repo = fakeRepo(`# widget

This paragraph explains **the reason** the skill exists, which is history.

**ok**

**A sentence long enough to look like a rule but which binds nobody to anything at all here.**
`);
  const texts = textsOf(extractContract(repo, 'widget'));
  assert.equal(texts.length, 0, `graded commentary as rules: ${JSON.stringify(texts)}`);
});

test('the one rule outranks the same sentence restated elsewhere', () => {
  const repo = fakeRepo(`# widget

## The one rule

**Never ship what you did not run.**

## Rules that are not negotiable

- **Never ship what you did not run.**
`);
  const contract = extractContract(repo, 'widget');
  const hits = contract.clauses.filter((c) => c.text === 'Never ship what you did not run.');
  assert.equal(hits.length, 1, 'a rule restated became two clauses, inflating every coverage number');
  assert.equal(hits[0].severity, 'critical');
  assert.equal(hits[0].tag, 'rule');
});

test('a press region is tagged and scored separately from the skill own rules', () => {
  const repo = fakeRepo(`# widget

**Never ship what you did not run.**

<!-- >>> press:agent-ui v0.8.1 sha256:deadbeef GENERATED by @natjswenson/press, do not edit -->
**Never print file contents into the conversation.**
<!-- <<< press:agent-ui -->
`);
  const contract = extractContract(repo, 'widget');
  const own = contract.clauses.find((c) => c.text.startsWith('Never ship'));
  const house = contract.clauses.find((c) => c.text.startsWith('Never print'));
  assert.equal(own.tag, 'skill');
  assert.equal(own.severity, 'high');
  assert.equal(house.tag, 'press');
  assert.equal(house.severity, 'medium', 'a shared presentation rule outranking a skill own rule makes severity meaningless');
});

test('an invariant fragment cut from a real clause is not counted twice', () => {
  const repo = fakeRepo(
    `# widget

**Never ship what you did not run, ever.**
`,
    { prose: [{ id: 'no-unrun-ship', pattern: 'Never ship what you did not run', rationale: 'the rule' }] },
  );
  const contract = extractContract(repo, 'widget');
  assert.equal(contract.clauses.length, 1, 'the invariant fragment padded the clause count with a duplicate');
});

test('an invariant that states something SKILL.md does not is kept', () => {
  const repo = fakeRepo(`# widget\n\n**Never ship what you did not run.**\n`, {
    prose: [{ id: 'separate', pattern: 'Always delete the branch after merging', rationale: 'cleanup' }],
  });
  const contract = extractContract(repo, 'widget');
  assert.equal(contract.clauses.length, 2);
  assert.ok(contract.clauses.some((c) => c.tag === 'inv'));
});

test('repo golden rules are pulled in, and only from the golden-rules section', () => {
  const repo = fakeRepo(
    `# widget\n\n**Never ship what you did not run.**\n`,
    null,
    `# CLAUDE.md

## Golden rules (read first)

- **Never push directly to \`main\`.**

## Some other section

- **Never read this section as a golden rule.**
`,
  );
  const contract = extractContract(repo, 'widget');
  const house = contract.clauses.filter((c) => c.tag === 'house');
  assert.equal(house.length, 1);
  assert.match(house[0].text, /Never push directly/);
});

test('clause ids are content-addressed, so reordering a file does not renumber them', () => {
  const a = clauseId('skill', 'Never ship what you did not run.');
  const b = clauseId('skill', '  never   SHIP what you did not run.  ');
  assert.equal(a, b, 'ids must survive whitespace and case, or every citation breaks on a reflow');
  assert.notEqual(a, clauseId('press', 'Never ship what you did not run.'));
});

test('a missing skill is an error, not an empty contract', () => {
  const repo = fakeRepo('# widget\n');
  assert.throws(() => extractContract(repo, 'nope'), /not a skill/);
});

