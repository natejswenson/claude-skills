/**
 * Cases — a finding turned into a test that is red today.
 *
 * A finding is an observation about one run; it evaporates. A case is the same
 * observation made permanent, and the only way to know a case is worth keeping
 * is to watch it fail. So generation here is inseparable from proving: the file
 * is written, the target skill's own runner is invoked on it, and if it passes
 * the file is deleted and the command exits non-zero.
 *
 * Refusing a green case looks pedantic until you notice what the alternative
 * produces — a growing folder of assertions that have never once been observed
 * failing, every one of which could be asserting nothing at all. That is the
 * decorative-eval failure this whole skill exists to make impossible, and
 * generating cases would otherwise be the fastest way to manufacture it.
 *
 * What the case asserts is judgment, supplied by the caller: a string that must
 * be absent from a committed file. The machine's job is only to prove that the
 * string is present today, so the assertion genuinely starts red.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const CASE_DIR = join('scripts', 'tests', 'generated');

export const caseTest = ({ id, skill, file, absent, clauseId, eventId, detail }) => `import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// Generated by eval from a real run of ${skill}.
//   finding ${id} — clause ${clauseId} broken at event ${eventId}
//   ${detail}
//
// This test was RED when it was generated: the string below was present, which
// is the defect. It is not a style preference and deleting it is not a fix.
const HERE = dirname(fileURLToPath(import.meta.url));
const SKILL = join(HERE, '..', '..', '..');

test('${id}: ${skill} no longer ${JSON.stringify(absent).slice(1, 60).replace(/'/g, "\\'")}…', () => {
  const body = readFileSync(join(SKILL, ${JSON.stringify(file)}), 'utf8');
  assert.ok(
    !body.includes(${JSON.stringify(absent)}),
    ${JSON.stringify(`${file} still contains the text this finding is about — ${detail}`)},
  );
});
`;

/**
 * Run one generated case in a clean process and report whether it passed AND
 * how many tests actually executed.
 *
 * The env scrub is load-bearing. `node --test` treats an inherited
 * NODE_TEST_CONTEXT as "you are already a test child", runs nothing, and exits
 * 0 — so a case proven from inside another test run would always look green and
 * always be refused, with a message confidently naming the wrong reason.
 */
export function proveCase(skillDir, path) {
  const env = { ...process.env };
  delete env.NODE_TEST_CONTEXT;
  delete env.NODE_OPTIONS;

  let output = '';
  let passed = true;
  try {
    output = execFileSync('node', ['--test', path], { cwd: skillDir, encoding: 'utf8', stdio: 'pipe', env });
  } catch (err) {
    passed = false;
    output = `${err.stdout ?? ''}${err.stderr ?? ''}`;
  }
  const ran = Number(/^# tests (\d+)$/m.exec(output)?.[1] ?? /tests (\d+)$/m.exec(output)?.[1] ?? 0);
  return { passed, ran, output };
}

/**
 * Write a case into the target skill and prove it fails there. Returns
 * {kept, path, reason}. Never leaves a green case on disk.
 */
export function generateCase(repo, { id, skill, file, absent, clauseId, eventId, detail, stack = 'node' }) {
  if (stack !== 'node') {
    throw new Error(
      `${skill} is a ${stack} skill — eval only generates node cases today, and emitting an unproven python case ` +
        'would be exactly the decorative eval this command exists to prevent.',
    );
  }
  const skillDir = join(repo, 'skills', skill, 'skills', skill);
  if (!existsSync(skillDir)) throw new Error(`no skill at ${skillDir}`);
  if (!existsSync(join(skillDir, file))) throw new Error(`--in ${file}: not a file inside ${skill}`);
  if (!absent || absent.length < 8) {
    throw new Error('--assert-absent needs a substring long enough to be specific; a short one will match by accident');
  }

  const dir = join(skillDir, CASE_DIR);
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${id}.test.mjs`);
  writeFileSync(path, caseTest({ id, skill, file, absent, clauseId, eventId, detail }));

  const { passed, ran } = proveCase(skillDir, path);

  // Anti-vacuity. A runner that executed zero tests exits 0, which is
  // indistinguishable from "the case passed" by exit code alone — and would
  // make every case look green on arrival and be refused for the wrong reason.
  // This is not hypothetical: `node --test` inherits NODE_TEST_CONTEXT when it
  // is spawned from inside another test run and reports success without
  // executing anything.
  if (ran === 0) {
    rmSync(path, { force: true });
    throw new Error(
      `the runner executed 0 tests for ${path}, so nothing was proven either way. ` +
        'Refusing to keep or refuse a case on a vacuous run.',
    );
  }

  if (passed) {
    rmSync(path);
    return {
      kept: false,
      path,
      reason:
        'the generated case PASSED on arrival, so it has never been observed failing and proves nothing. ' +
        `"${absent.slice(0, 60)}" is not present in ${file} today. Refused and removed.`,
    };
  }

  return { kept: true, path: path.slice(repo.length + 1), reason: 'observed failing against the skill as it exists today' };
}

/** Does this substring actually appear in the target file right now? */
export function isRedToday(repo, skill, file, absent) {
  const p = join(repo, 'skills', skill, 'skills', skill, file);
  return existsSync(p) && readFileSync(p, 'utf8').includes(absent);
}
