/**
 * Render a card model to markdown, and hash it.
 *
 * The hash is taken over the RENDERED CARD, never over the skill's source tree.
 * That distinction is the whole drift design: a comment typo inside a skill's
 * scripts changes its tree but changes no answer, and a gate that reddens on it
 * is a gate people learn to ignore. Drift means the answer would change.
 *
 * Nothing version-stamped by skillhelp itself may appear in the rendered bytes.
 * press learned this the expensive way: embedding a generator version in
 * generated output makes every release look like a content change to every
 * byte-comparison downstream.
 */
import { createHash } from 'node:crypto';
import { SECTIONS } from './extract.mjs';

const TITLE = {
  setup: 'Setup',
  usage: 'Usage',
  commands: 'Commands',
  architecture: 'Architecture',
  troubleshooting: 'Troubleshooting',
};

export function renderCard(card) {
  const out = [];
  out.push(`# ${card.name}`);
  out.push('');
  out.push('<!-- GENERATED by @natjswenson/skillhelp — do not edit. Run `skillhelp build`. -->');
  out.push('');
  out.push(`- **version** — ${card.version}`);
  out.push(`- **stack** — ${card.stack}`);
  if (card.summary) out.push(`- **summary** — ${card.summary}${card.summarySource ? ` \`${card.summarySource}\`` : ''}`);
  if (card.triggers.length) out.push(`- **triggers** — ${card.triggers.map((t) => `"${t}"`).join(', ')}`);
  out.push('');
  for (const s of SECTIONS) {
    out.push(`## ${TITLE[s]}`);
    out.push('');
    if (card.sections[s].length === 0) {
      // Stated, never padded. "No source in this skill's files" is a true and
      // useful answer; inventing plausible setup steps is the failure this
      // whole skill exists to refuse.
      out.push('_No source for this section in this skill\'s files._');
    } else {
      for (const f of card.sections[s]) out.push(`- ${f.text} \`${f.source}\``);
    }
    out.push('');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

export const hashCard = (text) => createHash('sha256').update(text).digest('hex').slice(0, 16);

export function manifestEntry(card, text) {
  return {
    name: card.name,
    version: card.version,
    stack: card.stack,
    cardHash: hashCard(text),
    facts: card.factCount,
    sections: Object.fromEntries(SECTIONS.map((s) => [s, card.sections[s].length])),
    emptySections: card.emptySections,
    secretsRefused: card.secretsRefused,
  };
}
